import { build } from 'esbuild';
import { resolve } from 'node:path';
const source = `
import assert from 'node:assert/strict';
import './src/game/killstreaks/effects/behavior.test';
import { GameClient } from './src/game/client';
import { isNetMessage } from './src/net/protocol';
import { localizeGameMessage } from './src/net/event-clock';
const client=new GameClient('self');
const self={id:'self',team:0,alive:true,hp:100,x:0,y:0,z:0,yaw:0,ack:0};
const enemy={id:'enemy',team:1,alive:true,hp:100,x:100,y:0,z:0,yaw:0,ack:0};
const sample={id:'enemy',x:50,y:0,z:10,source:'recon',pulse:1,expiresAt:10500};
const radar={type:'radar-state',at:10000,actorId:'self',samples:[sample]};
assert(isNetMessage(radar));
client.applySnapshot({at:10000,players:[self,enemy]});
assert.equal(client.view().blips.filter(b=>b.kind==='enemy').length,0,'distant quiet enemy hidden');
client.applySnapshot({at:10000,radar:[sample]});
assert.equal(client.view().blips.find(b=>b.id==='enemy').x,50,'sensor uses pulse position');
client.applySnapshot({at:10100,players:[self,{...enemy,x:120}]});
assert.equal(client.view().blips.find(b=>b.id==='enemy').x,50,'movement cannot make radar a continuous wallhack');
client.applySnapshot({at:10600});
assert.equal(client.view().blips.filter(b=>b.kind==='enemy').length,0,'pulse expires');
const localized=localizeGameMessage(radar,2000);
assert.equal(localized.at,8000);assert.equal(localized.samples[0].expiresAt,8500);
assert.equal(localized.samples[0].expiresAt-localized.at,500,'host clock span preserved');
assert(!isNetMessage({...radar,samples:[{...sample,x:NaN}]}));
assert(!isNetMessage({...radar,samples:new Array(65).fill(sample)}));
const mortar={type:'effect',e:{type:'mortar-impact',at:1000,instanceId:1,actorId:'self',team:0,streakId:'blast-mortar',index:0,x:2,y:0,z:3,victims:1}};
assert(isNetMessage(mortar),'real mortar impacts replicated');
assert(!isNetMessage({...mortar,e:{...mortar.e,index:-1}}));
assert(!isNetMessage({...mortar,e:{...mortar.e,streakId:undefined}}));
const fx={type:'streak-effects',at:10000,effects:[{kind:'sentry',instanceId:1,actorId:'self',team:0,streakId:'sentry-post',x:1,y:0,z:3,remainingMs:30000,yaw:1,shots:2}]};
assert(isNetMessage(fx));
assert(!isNetMessage({...fx,effects:[{...fx.effects[0],yaw:Infinity}]}));
const earned={type:'streak-earned',at:11000,actorId:'self',team:0,streakId:'recon-sweep',slot:1,charges:1};
const state={type:'streak-state',at:11000,actorId:'self',kills:3,slots:[],cause:earned,causeId:JSON.stringify(earned)};
client.applyEvent(earned);client.drain();
for(let i=0;i<100;i++)client.applySnapshot({at:11000+i,streak:state});
assert.equal(client.drain().filter(e=>e.kind==='feed').length,0,'direct event not replayed by level snapshots');
const remote=new GameClient('self');
remote.applySnapshot({at:9000,streak:localizeGameMessage(state,2000)});remote.drain();
remote.applySnapshot({at:9001,streak:localizeGameMessage(state,1990)});
assert.equal(remote.drain().filter(e=>e.kind==='feed').length,0,'clock correction cannot replay HUD cause');
console.log('PASS sensor wire: pulse positions, expiry, clock conversion, finite bounded effects and real mortar payload');
`;
const out=await build({stdin:{contents:source,loader:'ts',resolveDir:resolve('.')},bundle:true,platform:'node',format:'esm',write:false,logLevel:'warning'});
await import('data:text/javascript;base64,'+Buffer.from(out.outputFiles[0].contents).toString('base64'));
